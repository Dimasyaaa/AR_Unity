-- Support two API-served photo pages for each cabinet while preserving the
-- legacy reference_photo column used by existing SQLite exports and builds.

BEGIN;

CREATE TABLE IF NOT EXISTS cabinet_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabinet_id BIGINT NOT NULL REFERENCES cabinet_profiles(id) ON DELETE CASCADE,
    page_number SMALLINT NOT NULL CHECK (page_number IN (1, 2)),
    image_data BYTEA NOT NULL,
    content_type TEXT NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    caption TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_cabinet_photos_page UNIQUE (cabinet_id, page_number)
);

INSERT INTO cabinet_photos (cabinet_id, page_number, image_data, content_type, caption)
SELECT id, 1, reference_photo, reference_photo_content_type, 'Лист 1'
FROM cabinet_profiles
WHERE reference_photo IS NOT NULL
ON CONFLICT (cabinet_id, page_number) DO NOTHING;

INSERT INTO app_schema_migrations (version)
VALUES ('004_cabinet_photo_pages')
ON CONFLICT (version) DO NOTHING;

COMMIT;
