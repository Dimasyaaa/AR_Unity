-- Run once against the PostgreSQL database after backing it up.
-- This migration only adds inventory tables; it does not modify existing users or QR records.

BEGIN;

CREATE TABLE IF NOT EXISTS app_schema_migrations (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cabinet_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_code_id BIGINT NOT NULL UNIQUE REFERENCES qr_codes(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    reference_photo BYTEA,
    reference_photo_content_type TEXT NOT NULL DEFAULT 'image/jpeg',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_cabinet_photo_content_type
        CHECK (reference_photo_content_type IN ('image/jpeg', 'image/png', 'image/webp'))
);

CREATE TABLE IF NOT EXISTS cabinet_checklist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cabinet_id BIGINT NOT NULL REFERENCES cabinet_profiles(id) ON DELETE CASCADE,
    item_name TEXT NOT NULL,
    description TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_cabinet_checklist_item_name UNIQUE (cabinet_id, item_name)
);

CREATE TABLE IF NOT EXISTS inventory_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_run_id UUID NOT NULL UNIQUE,
    cabinet_id BIGINT NOT NULL REFERENCES cabinet_profiles(id) ON DELETE RESTRICT,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    qr_code_id BIGINT NOT NULL REFERENCES qr_codes(id) ON DELETE RESTRICT,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_inventory_run_times CHECK (completed_at >= started_at)
);

CREATE INDEX IF NOT EXISTS ix_inventory_runs_cabinet_completed
    ON inventory_runs (cabinet_id, completed_at DESC);
CREATE INDEX IF NOT EXISTS ix_inventory_runs_user_completed
    ON inventory_runs (user_id, completed_at DESC);

CREATE TABLE IF NOT EXISTS inventory_run_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_run_id BIGINT NOT NULL REFERENCES inventory_runs(id) ON DELETE CASCADE,
    checklist_item_id BIGINT NOT NULL REFERENCES cabinet_checklist_items(id) ON DELETE RESTRICT,
    item_name_snapshot TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('present', 'missing')),
    comment TEXT,
    CONSTRAINT uq_inventory_run_item UNIQUE (inventory_run_id, checklist_item_id)
);

CREATE INDEX IF NOT EXISTS ix_inventory_run_items_status
    ON inventory_run_items (status, inventory_run_id);

INSERT INTO app_schema_migrations (version)
VALUES ('001_cabinet_inventory')
ON CONFLICT (version) DO NOTHING;

COMMIT;
